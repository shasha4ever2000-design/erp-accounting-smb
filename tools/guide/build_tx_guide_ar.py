def money(n):
    return f'{n:,.2f}'


def render_tx(t, num):
    ex = MAN.get(t.key)
    entries = ex['entries'] if ex else []
    posts = len(entries) > 0
    out = [f'<div class="tx">']
    out.append(f'<div class="tx-head"><span class="tx-num">{num}</span>'
               f'<h3>{esc(t.title)}</h3>'
               f'<span class="chip {"posts" if posts else "noposts"}">'
               f'{"يُرحَّل إلى الدفتر" if posts else "لا يُرحِّل شيئاً"}</span></div>')

    out.append(f'<div class="scenario"><span class="lbl">المثال</span><p>{t.scenario}</p></div>')

    if t.where:
        out.append('<div class="two-col"><div>')
        out.append('<h4>طريقة الإدخال</h4><ol class="steps">')
        for w in t.where:
            out.append(f'<li>{w}</li>')
        out.append('</ol></div>')
        if t.figures:
            out.append('<div><h4>باختصار</h4><ul class="figs">')
            for f in t.figures:
                out.append(f'<li>{esc(f)}</li>')
            out.append('</ul></div>')
        else:
            out.append('<div></div>')
        out.append('</div>')

    if t.doc and (not posts or t.show_doc):
        p = f'img/doc-{t.doc}.jpg'
        if os.path.exists(os.path.join(DIR, 'txweb', p)):
            out.append(f'<figure class="doc"><img src="{p}" alt="{esc(t.title)}">'
                       f'<figcaption>الشاشة التي يُدخَل منها</figcaption></figure>')

    if posts:
        out.append('<h4 class="post-h">ما الذي يُرحَّل</h4>')
        for je in entries:
            p = f'img/je-{je["number"]}.jpg'
            if os.path.exists(os.path.join(DIR, 'txweb', p)):
                out.append(f'<figure class="je"><img src="{p}" alt="{je["number"]}"></figure>')
            else:
                rows = ''.join(
                    f'<tr><td>{esc(l["account"])}</td>'
                    f'<td class="r">{money(l["debit"]) if l["debit"] else "—"}</td>'
                    f'<td class="r">{money(l["credit"]) if l["credit"] else "—"}</td></tr>'
                    for l in je['lines'])
                out.append(f'<table class="je-fallback"><tr><th>الحساب</th><th class="r">مدين</th>'
                           f'<th class="r">دائن</th></tr>{rows}</table>')
    else:
        out.append('<div class="nopost">تسجّل هذه الخطوة مستنداً دون أن تكتب قيد يومية.</div>')

    out.append(f'<div class="why"><span class="lbl">لماذا</span><p>{t.why}</p></div>')
    out.append('</div>')
    return '\n'.join(out)


def reference_table():
    rows = []
    n = 0
    for ch in CHAPTERS:
        for t in ch['txs']:
            n += 1
            ex = MAN.get(t.key)
            if not ex or not ex['entries']:
                rows.append(f'<tr><td>{n}</td><td>{esc(t.title)}</td>'
                            f'<td colspan="2" class="none">لا يوجد قيد</td></tr>')
                continue
            for je in ex['entries']:
                drs = [l for l in je['lines'] if l['debit']]
                crs = [l for l in je['lines'] if l['credit']]
                dr = '<br>'.join(f'{esc(l["account"])} {money(l["debit"])}' for l in drs)
                cr = '<br>'.join(f'{esc(l["account"])} {money(l["credit"])}' for l in crs)
                rows.append(f'<tr><td>{n}</td><td>{esc(t.title)}<br><span class="jenum">{je["number"]}</span></td>'
                            f'<td class="dr">{dr}</td><td class="cr">{cr}</td></tr>')
    return ('<table class="ref"><tr><th>#</th><th>المعاملة</th><th>مدين</th><th>دائن</th></tr>'
            + ''.join(rows) + '</table>')


