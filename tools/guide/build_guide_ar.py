def render_module(m):
    out = ['<div class="module">']
    out.append(f'<h3>{esc(m.title)}</h3>')
    out.append(f'<p class="purpose">{m.purpose}</p>')
    img = f'{IMG}/{m.img}.jpg'
    if os.path.exists(os.path.join('web-ar', img)):
        out.append(f'<figure><img src="{img}" alt="{esc(m.title)}"></figure>')
    if m.steps:
        out.append('<ol class="steps">')
        for s in m.steps:
            out.append(f'<li>{s}</li>')
        out.append('</ol>')
    if m.posts:
        out.append('<table class="posting small"><tr><th>مدين</th><th>دائن</th></tr>')
        for d, c in m.posts:
            out.append(f'<tr><td>{d}</td><td>{c}</td></tr>')
        out.append('</table>')
    if m.tip:
        out.append(f'<p class="tip"><b>ملاحظة.</b> {m.tip}</p>')
    out.append('</div>')
    return '\n'.join(out)


